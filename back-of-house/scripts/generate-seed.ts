// Turns lib/seed.ts into supabase/seed.sql, so demo mode and Supabase start from the same café.
// Run: npm run seed:sql
import { SEED_INVENTORY, SEED_MENU, SEED_STAFF } from "../lib/seed.ts";

const q = (v: unknown): string =>
  v === null || v === undefined ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v) : `'${String(v).replace(/'/g, "''")}'`;

const out: string[] = ["-- Generated by scripts/generate-seed.ts. Edit lib/seed.ts instead.", "begin;", ""];

out.push("insert into staff (id, name, role, pin_hash) values");
out.push(SEED_STAFF.map((s) => `  (${q(s.id)}, ${q(s.name)}, ${q(s.role)}, crypt(${q(s.pin)}, gen_salt('bf')))`).join(",\n") + ";", "");

out.push("insert into inventory_items (id, name, category, unit, quantity, reorder_at, par, pack_size, pack_label, supplier) values");
out.push(
  SEED_INVENTORY.map((i) => `  (${[i.id, i.name, i.category, i.unit, i.quantity, i.reorderAt, i.par, i.packSize, i.packLabel, i.supplier].map(q).join(", ")})`).join(",\n") + ";",
  "",
);

out.push("insert into menu_items (id, name, category, temp, price, sugar_free, dairy_free, caffeine, comfort) values");
out.push(
  SEED_MENU.map((m) => `  (${[m.id, m.name, m.category, m.temp, m.price, m.sugarFree, m.dairyFree, m.caffeine, !!m.comfort].map(q).join(", ")})`).join(",\n") + ";",
  "",
);

out.push("insert into recipe_ingredients (menu_item_id, inventory_item_id, amount) values");
out.push(SEED_MENU.flatMap((m) => Object.entries(m.uses).map(([inv, amt]) => `  (${q(m.id)}, ${q(inv)}, ${amt})`)).join(",\n") + ";", "");

out.push("insert into recipe_steps (menu_item_id, position, instruction, seconds, tip) values");
out.push(
  SEED_MENU.flatMap((m) => m.steps.map((s, i) => `  (${q(m.id)}, ${i + 1}, ${q(s.text)}, ${q(s.seconds ?? null)}, ${q(s.tip ?? null)})`)).join(",\n") + ";",
  "",
);

out.push("commit;", "");
console.log(out.join("\n"));
